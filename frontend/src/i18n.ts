export type Key = keyof typeof messages
export type Language = 'en' | 'ru'
export type Theme = 'system' | 'light' | 'dark'

export function browserLanguage(value: string): Language {
  return value.toLowerCase().split('-')[0] === 'ru' ? 'ru' : 'en'
}

export function translate(language: Language, key: string): string {
  if (!(key in messages) || !Object.hasOwn(messages, key)) return key
  return messages[key as Key][language === 'ru' ? 1 : 0]
}

export function dateTime(language: Language, value: string, timeZone?: string): string {
  return new Intl.DateTimeFormat(language, { dateStyle: 'medium', timeStyle: 'short', timeZone }).format(new Date(value))
}

export function localInputDate(value: Date, withSeconds = false): string {
  const local = new Date(value.getTime() - value.getTimezoneOffset() * 60000)
  return local.toISOString().slice(0, withSeconds ? 23 : 16)
}

export function rankRange(rank: number, end: number): string {
  return end === rank ? String(rank) : `${rank}–${end}`
}

export const I18n = createContext({ language: 'en' as Language, t: (key: string) => translate('en', key) })
export function useI18n() {
  return useContext(I18n)
}
